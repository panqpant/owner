def emerald(sprite):
    if sprite in SPRITES: return 'OBJ_EVENT_GFX_' + SPRITES[sprite]
    m = re.match(r'SPRITE_GSLEADER(\d+)', sprite)
    if m: return 'OBJ_EVENT_GFX_' + LEADERS[(int(m.group(1)) - 1) % 8]
    m = re.match(r'SPRITE_FOLLOWER_MON_STATIC_(\w+)', sprite)
    if m: return 'OBJ_EVENT_GFX_' + MONS.get(m.group(1), 'POOCHYENA')
    if 'WOMAN' in sprite or 'GIRL' in sprite or 'W' == sprite[-1]: return 'OBJ_EVENT_GFX_WOMAN_2'
    return 'OBJ_EVENT_GFX_MAN_1'

