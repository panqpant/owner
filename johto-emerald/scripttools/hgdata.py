def species(s):
    if s in _have('SPECIES'): return s
    b = s.replace('SPECIES_', '')
    if b in GEN4_SPECIES: return 'SPECIES_' + GEN4_SPECIES[b]
    return 'SPECIES_UNOWN' if b.startswith('UNOWN') else 'SPECIES_NONE'

def move(m):
    if m in _have('MOVE'): return m
    b = m.replace('MOVE_', '')
    return 'MOVE_' + GEN4_MOVES[b] if b in GEN4_MOVES and 'MOVE_' + GEN4_MOVES[b] in _have('MOVE') else 'MOVE_NONE'

def item(i):
    if i in _have('ITEM'): return i
    j = GEN4_ITEMS.get(i)
    return j if j and j in _have('ITEM') else 'ITEM_NONE'
