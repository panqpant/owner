ICE_PATH = R('ZUBAT GOLBAT SWINUB JYNX DELIBIRD SNEASEL SWINUB ZUBAT DELIBIRD JYNX SNEASEL PILOSWINE')
ROCKET_HIDEOUT = R('KOFFING VOLTORB GEODUDE RATICATE GRAVELER KOFFING VOLTORB GRAVELER WEEZING ELECTRODE MAGCARGO MUK')

p = root + '/src/data/wild_encounters.json'
text = open(p).read()
# Edit the text in place (not json.dump) so the file keeps upstream formatting
done = set()
def rewrite(block):
    m = re.search(r'"map": "(\w+)"', block).group(1)
    roster = ROSTERS.get(m)
    if m.startswith('MAP_VICTORY_ROAD'): roster = VICTORY_ROAD
    if m.startswith('MAP_SHOAL_CAVE'): roster = ICE_PATH
    if m.startswith('MAP_MAGMA_HIDEOUT'): roster = ROCKET_HIDEOUT
    if not roster or '"land_mons"' not in block:
        return block
    head, land = block.split('"land_mons"', 1)
    land_end = land.index(']')
    it = iter(roster)
    land = re.sub(r'"species": "SPECIES_\w+"', lambda _: '"species": "SPECIES_%s"' % next(it), land[:land_end]) + land[land_end:]
    done.add(m)
    return head + '"land_mons"' + land
parts = re.split(r'(?=\{\s*"map": "MAP_)', text)
text = ''.join(rewrite(x) if re.match(r'\{\s*"map": "MAP_', x) else x for x in parts)
missing = set(ROSTERS) - done
assert not missing, missing
open(p, 'w').write(text)
print('wild ok', len(done))
