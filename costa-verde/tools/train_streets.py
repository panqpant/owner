"""Tune Streets.luau parameters per district style so generated networks match real US statistics.
Usage: python tools/train_streets.py [evals_per_role]
-> src/shared/Gen/StreetStyles.luau (tuned params), tools/data/street_training.json, screenshots/streets_compare.png"""
import json
import math
import random
import subprocess
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, "tools")
from road_stats import stats  # noqa: E402

TARGET = json.load(open("tools/data/road_stats.json"))
try:
    PREV = json.load(open("tools/data/street_training.json"))
except FileNotFoundError:
    PREV = {}
BOUNDS = {
    "spacing": (150, 1800), "order": (0, 1), "curve": (0, 0.6), "branch": (0.1, 1), "cross": (0, 1),
    "deadEnd": (0, 0.6), "connect": (0.2, 0.9), "maxLen": (1, 14), "collectors": (2, 14), "aspect": (1, 3),
}
HALF = {"rural": 12000}


def run(role, params, seed=7):
    half = HALF.get(role, 4000)
    json.dump({"half": half, "params": params, "seed": seed, "angle": 0.3}, open("build/p.json", "w"))
    subprocess.run(["lune", "run", "tools/gen-streets.luau", "build/p.json", "build/s.json"], check=True)
    d = json.load(open("build/s.json"))
    return d, stats(d["roads"], d["half"])


def loss(s, t):
    e = abs(math.log(max(s["density_km_per_km2"], 0.01) / t["density_km_per_km2"]))
    e += abs(math.log(max(s["block_median"], 1) / t["block_median"]))
    e += 10 * abs(s["straightness"] - t["straightness"])
    e += 3 * (abs(s["dead_end_frac"] - t["dead_end_frac"]) + abs(s["t_frac"] - t["t_frac"]) + abs(s["cross_frac"] - t["cross_frac"]))
    e += 3 * abs(s["orientation_order"] - t["orientation_order"])
    return e


def clamp(p):
    out = {}
    for k, (lo, hi) in BOUNDS.items():
        out[k] = min(hi, max(lo, p[k]))
    out["maxLen"] = round(out["maxLen"])
    out["collectors"] = round(out["collectors"])
    return out


def tune(role, evals):
    t = TARGET["roles"][role]
    if role == "rural":  # rural roads stay on the field lattice (real county grids are fairly regular)
        BOUNDS["order"] = (0.6, 1)
    else:
        BOUNDS["order"] = (0, 1)
    rnd = random.Random(zlib.crc32(role.encode()))  # deterministic (str hash is randomized per process)
    best = clamp({"spacing": t["block_median"], "order": t["orientation_order"], "curve": 0.05, "branch": 0.7,
                  "cross": t["cross_frac"] * 2, "deadEnd": t["dead_end_frac"] / 2, "connect": 0.5, "maxLen": 6, "collectors": 6, "aspect": 1.8})
    best_l = loss(run(role, best)[1], t)
    # second start shaped like a real suburb pod: curving collectors, many short cul-de-sac fingers
    pod = clamp({"spacing": t["block_median"], "order": 0.3, "curve": 0.3, "branch": 0.9, "cross": 0.1,
                 "deadEnd": 0.6, "connect": 0.5, "maxLen": 1, "collectors": 4, "aspect": 1.5})
    pod_l = loss(run(role, pod)[1], t)
    if pod_l < best_l:
        best, best_l = pod, pod_l
    # third start: last run's best, so retraining never loses ground
    if role in PREV:
        prev = clamp({**best, **PREV[role]["params"]})
        prev_l = (loss(run(role, prev, 7)[1], t) + loss(run(role, prev, 11)[1], t)) / 2
        if prev_l < best_l:
            best, best_l = prev, prev_l
    step = 0.35
    for i in range(evals):
        cand = {k: v + rnd.gauss(0, step) * (BOUNDS[k][1] - BOUNDS[k][0]) * (0.5 if k == "spacing" else 1) for k, v in best.items()}
        cand = clamp(cand)
        l = (loss(run(role, cand, 7)[1], t) + loss(run(role, cand, 11)[1], t)) / 2  # two seeds: robust params
        if l < best_l:
            best, best_l = cand, l
        step = max(0.04, step * 0.97)
    return best, best_l


def main():
    evals = int(sys.argv[1]) if len(sys.argv) > 1 else 80
    result = {}
    for role in TARGET["roles"]:
        p, l = tune(role, evals)
        s = run(role, p)[1]
        result[role] = {"params": p, "loss": l, "stats": s, "target": TARGET["roles"][role]}
        print(f"{role:9s} loss {l:.2f}  " + "  ".join(f"{k[:8]} {s[k]:.2f}/{TARGET['roles'][role][k]:.2f}" for k in
              ["density_km_per_km2", "block_median", "dead_end_frac", "t_frac", "cross_frac", "orientation_order"]))
    json.dump(result, open("tools/data/street_training.json", "w"), indent=1)
    with open("src/shared/Gen/StreetStyles.luau", "w") as fh:
        fh.write("-- Generated by tools/train_streets.py: street growth params per district style, tuned so the\n"
                 "-- networks match real US road statistics (tools/road_stats.py). Do not edit by hand.\nreturn {\n")
        for role, r in result.items():
            fh.write(f"\t{role} = {{ " + ", ".join(f"{k} = {v:.3f}" if isinstance(v, float) else f"{k} = {v}" for k, v in r["params"].items()) + " },\n")
        fh.write("}\n")
    preview(result)


def preview(result):
    """Real (top) vs generated (bottom), same window per style, each tile clipped."""
    roles = list(result)
    T = 360
    img = Image.new("RGB", (len(roles) * T, 2 * T + 44), (245, 243, 236))
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype("DejaVuSans.ttf", 14)
    for i, role in enumerate(roles):
        name = next(n for n, v in TARGET["templates"].items() if v["role"] == role)
        real = json.load(open(f"tools/data/roads/{name}.json"))
        gen = run(role, result[role]["params"])[0]
        view = 4000 if role != "rural" else 16000
        for row, net in enumerate([real, gen]):
            tile = Image.new("RGB", (T, T), (245, 243, 236))
            td = ImageDraw.Draw(tile)
            for rd in net["roads"]:
                pts = [((x / view + 0.5) * T, (z / view + 0.5) * T) for x, z in rd["pts"]]
                if len(pts) > 1:
                    td.line(pts, fill=(200, 80, 40) if rd["kind"] in ("arterial", "county") and row else (40, 40, 50), width=2 if rd["kind"] == "arterial" else 1)
            img.paste(tile, (i * T, row * (T + 22)))
            d.text((i * T + 6, row * (T + 22) + T + 3), f"{'REAL' if row == 0 else 'OURS'} {role}", fill=(0, 0, 0) if row == 0 else (150, 40, 0), font=font)
        d.line([(i * T, 0), (i * T, 2 * T + 44)], fill=(160, 160, 160), width=2)
    img.save("screenshots/streets_compare.png")
    print("wrote screenshots/streets_compare.png")


if __name__ == "__main__":
    main()
