"""Re-import every exported block FBX, check each part's position against the manifests and record its true size
(studs, Roblox axes), so the Roblox loader can correct any unit-scale mix-up from the importer.
Usage (from costa-verde/, after both exports): python tools/blender/check_block_export.py"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import bpy  # noqa: E402
from mathutils import Vector  # noqa: E402
from render_world import reset  # noqa: E402

OFFSET = -40960 / 2


def measure(path):
    """{object name: (centre in Roblox coords, size in Roblox axes)} for one FBX."""
    reset()
    bpy.ops.import_scene.fbx(filepath=path)
    out = {}
    for o in bpy.context.scene.objects:
        if o.type != "MESH":
            continue
        bb = [o.matrix_world @ Vector(v) for v in o.bound_box]
        lo = Vector((min(v.x for v in bb), min(v.y for v in bb), min(v.z for v in bb)))
        hi = Vector((max(v.x for v in bb), max(v.y for v in bb), max(v.z for v in bb)))
        c, d = (lo + hi) / 2, hi - lo
        out[o.name.split(".")[0]] = ([c.x + OFFSET, c.z, -c.y + OFFSET], [round(d.x, 3), round(d.z, 3), round(d.y, 3)])
    return out


def check(manifest_path, luau_path, entries):
    worst = 0.0
    for path, key, rec in entries:
        got = measure(path)
        if key not in got:
            print("MISSING object", key, "in", path)
            continue
        c, size = got[key]
        if "center" in rec:
            worst = max(worst, max(abs(a - b) for a, b in zip(c, rec["center"])))
        rec["size"] = size
    print(f"{manifest_path}: {len(entries)} parts checked, worst position mismatch {worst:.3f} studs")
    return worst


def main():
    bm = "build/roblox_block/manifest.json"
    if os.path.exists(bm):
        man = json.load(open(bm))
        entries = []
        for b in man["buildings"]:
            for role, rec in b["parts"].items():
                entries.append((f"build/roblox_block/{b['id']}.fbx", f"{b['id']}_{role}", rec))
        w = check(bm, "src/shared/BlockManifest.luau", entries)
        assert w < 0.05, "building part positions don't match the manifest"
        json.dump(man, open(bm, "w"), indent=1)
        open("src/shared/BlockManifest.luau", "w").write("-- Generated by tools/blender/export_block_roblox.py (+ sizes from check_block_export.py). Do not edit.\nreturn [==[" + json.dumps(man) + "]==]\n")
    em = "build/roblox_block/env/manifest.json"
    if os.path.exists(em):
        env = json.load(open(em))
        entries = [(f"build/roblox_block/env/{s['name']}.fbx", s["name"], s) for s in env["surfaces"]]
        entries += [(f"build/roblox_block/env/{k}.fbx", k, v) for k, v in env["models"].items()]
        w = check(em, "src/shared/BlockEnvManifest.luau", entries)
        assert w < 0.05, "surface positions don't match the manifest"
        json.dump(env, open(em, "w"), indent=1)
        open("src/shared/BlockEnvManifest.luau", "w").write("-- Generated by tools/blender/export_block_env.py (+ sizes from check_block_export.py). Do not edit.\nreturn [==[" + json.dumps(env) + "]==]\n")
    _ = glob


main()
