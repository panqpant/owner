"""Batch 10: the city's performance budget. Counts placed triangles and parts per district from the
layout and the exported asset metadata, writes art/BUDGET.md, and fails if a district goes over.

Run:  python map/budget.py      (plain Python, after map/build_map.py)
"""

import collections
import glob
import json
import os
import sys

ART = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYOUT = os.path.join(os.path.dirname(ART), "src", "map", "Layout.luau")

# Streaming (StreamingTargetRadius 1024) keeps roughly one district around a player, and Roblox's
# automatic mesh LOD cuts distant meshes further, so a district's raw total is a safe worst case.
DISTRICT_TRIANGLES = 3_500_000
CITY_PARTS = 12_000


def load():
    assets = {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(os.path.join(ART, "export", "*.json"))}
    s = open(LAYOUT).read()
    layout = json.loads(s[s.index("[==[") + 4 : s.rindex("]==]")])
    return assets, layout


def tally(assets, layout):
    per = collections.defaultdict(lambda: {"items": 0, "tris": 0, "parts": 0})
    by_asset = collections.Counter()
    for it in layout["items"]:
        a = assets[it["a"]]
        p = per[it["d"]]
        p["items"] += 1
        p["tris"] += a["triangles"]
        p["parts"] += len(a["parts"])
        by_asset[it["a"]] += 1
    return per, by_asset


def main():
    assets, layout = load()
    per, by_asset = tally(assets, layout)
    total_tris = sum(p["tris"] for p in per.values())
    total_parts = sum(p["parts"] for p in per.values())
    lines = [
        "# City budget",
        "",
        "Generated by `art/map/budget.py`. Raw totals, before Roblox's streaming and automatic LOD.",
        "",
        f"Limits: {DISTRICT_TRIANGLES / 1e6:.1f}M triangles per district, {CITY_PARTS:,} parts for the city.",
        "",
        "| District | Placements | Triangles | Parts |",
        "|---|---:|---:|---:|",
    ]
    for d, p in sorted(per.items(), key=lambda kv: -kv[1]["tris"]):
        lines.append(f"| {d} | {p['items']:,} | {p['tris'] / 1e6:.2f}M | {p['parts']:,} |")
    lines += [f"| **City** | {sum(p['items'] for p in per.values()):,} | {total_tris / 1e6:.2f}M | {total_parts:,} |", "", "Heaviest assets (placed triangles):", ""]
    rows = sorted(((assets[a]["triangles"] * n, a, n) for a, n in by_asset.items()), reverse=True)[:10]
    lines += [f"- {a}: {n} x {assets[a]['triangles']:,} = {t / 1e6:.2f}M" for t, a, n in rows]
    out = os.path.join(ART, "BUDGET.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    over = [d for d, p in per.items() if p["tris"] > DISTRICT_TRIANGLES]
    assert not over, f"over the triangle budget: {over}"
    assert total_parts <= CITY_PARTS, f"{total_parts} parts is over {CITY_PARTS}"
    print("budget OK")


if __name__ == "__main__":
    sys.exit(main())
