#!/usr/bin/env python3
"""Renders printable ASCII from a monospace TTF into app/font8x16.h (1 bit per pixel, 8x16 cells)."""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
out = sys.argv[2] if len(sys.argv) > 2 else "app/font8x16.h"
font = ImageFont.truetype(ttf, 14)

rows = []
for code in range(32, 127):
    img = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(img).text((0, -2), chr(code), font=font, fill=255)
    glyph = []
    for y in range(16):
        bits = 0
        for x in range(8):
            if img.getpixel((x, y)) >= 110:
                bits |= 0x80 >> x
        glyph.append(bits)
    rows.append(glyph)

with open(out, "w") as f:
    f.write("// Generated by tools/gen_font.py from DejaVu Sans Mono Bold. ASCII 32..126, 8x16, MSB = left pixel.\n")
    f.write("#pragma once\n#include <stdint.h>\n\nstatic const uint8_t kFont8x16[95][16] = {\n")
    for code, glyph in zip(range(32, 127), rows):
        f.write("    {" + ", ".join(f"0x{b:02X}" for b in glyph) + "}, // " + repr(chr(code)) + "\n")
    f.write("};\n")
