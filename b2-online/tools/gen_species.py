#!/usr/bin/env python3
"""Writes app/species.h (English names of national dex 1..649) from PokeAPI's pokemon_species_names.csv."""
import csv, sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "app/species.h"
names = {}
with open(src, encoding="utf-8") as f:
    for row in csv.DictReader(f):
        if row["local_language_id"] == "9":
            names[int(row["pokemon_species_id"])] = row["name"]
fix = {"♀": " F", "♂": " M", "é": "e", "’": "'"}
with open(out, "w") as f:
    f.write("// Generated by tools/gen_species.py from PokeAPI data. National dex 1..649 (Gen 1-5).\n")
    f.write("#pragma once\n\nstatic const char* const kSpeciesNames[650] = {\n    \"-\",\n")
    for i in range(1, 650):
        n = names[i]
        for a, b in fix.items():
            n = n.replace(a, b)
        assert n.isascii(), n
        f.write(f'    "{n}",\n')
    f.write("};\n")
